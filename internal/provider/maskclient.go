package provider

import (
	"context"
	"fmt"
	"log"
	"net/http"
	"time"

	"github.com/yetone/magpie/internal/fingerprint"
	"github.com/yetone/magpie/internal/nativeclient"
)

// MaskProtocol is the custom provider API whose requests the user opted
// to identify as a coding client. Other APIs keep their usual behavior.
func (p Provider) MaskProtocol() Protocol {
	if p.Account != nil || p.Preset != "" {
		return ""
	}
	switch {
	case p.BaseAPI == "responses" && p.Responses != "" && p.MaskClient == ClientCodex:
		return Responses
	case p.BaseAPI == "anthropic" && p.Anthropic != "" && p.MaskClient == ClientClaudeCode:
		return Anthropic
	}
	return ""
}

// DoNative forwards inference using only the custom provider's connection and
// explicit headers. Client identity is generated by the selected executable.
func (p Provider) DoNative(ctx context.Context, proto Protocol, body []byte, scope string, betas []string, admit func(context.Context) error) (*http.Response, error) {
	if p.MaskProtocol() != proto || proto == "" {
		return nil, fmt.Errorf("native fingerprint is not enabled for %s", proto)
	}
	return fingerprint.Do(ctx, nativeclient.Options{Client: p.MaskClient, Base: p.Base(proto), Key: p.Key, Headers: p.Headers, Proxy: p.ProxyChoice(), Scope: scope, Betas: betas, Pool: nativeclient.FromContext(ctx), BeforeSend: admit}, body)
}

// KeepNative warms enabled custom clients at gateway startup and after a
// version or provider change. It reads stored providers, not subscription
// discovery. Each successful build is loaded once, then its process exits.
func KeepNative(ctx context.Context) {
	warmed := map[string]bool{}
	tick := time.NewTicker(time.Minute)
	defer tick.Stop()
	for {
		clients := map[string]bool{}
		for _, p := range load().Providers {
			if !p.Off && p.MaskProtocol() != "" {
				clients[p.MaskClient] = true
			}
		}
		for _, client := range []string{fingerprint.Codex, fingerprint.Claude} {
			if !clients[client] || ctx.Err() != nil {
				continue
			}
			warm, cancel := context.WithTimeout(ctx, 30*time.Second)
			err := fingerprint.Warm(warm, client, warmed)
			cancel()
			if err != nil && ctx.Err() == nil {
				log.Printf("native fingerprint %s warmup: %v", client, err)
			}
		}
		select {
		case <-ctx.Done():
			return
		case <-tick.C:
		}
	}
}
